'use strict';
// Generates backend/.env with two independent random keys. Refuses to overwrite: rotating the file key
// would make every stored document unreadable, and rotating the audit key would break verification.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const file = path.resolve(__dirname, '..', '.env');
const key = () => crypto.randomBytes(32).toString('hex');

if (process.argv.includes('--generate') || process.argv.includes('--print')) {
  const fileKey = key();
  let auditKey = key();
  while (auditKey === fileKey) auditKey = key();
  console.log('--- Generated Keys for Production (e.g. Render Dashboard) ---');
  console.log('AUDIT_HMAC_KEY=' + auditKey);
  console.log('FILE_ENC_KEY=' + fileKey);
  console.log('-------------------------------------------------------------');
  console.log('Copy the values above into Render > Environment Variables.');
  console.log('Keep them secure and backed up. Never commit secrets to Git.');
  process.exit(0);
}

if (process.argv.includes('--show-existing')) {
  if (!fs.existsSync(file)) {
    console.error('No .env file found at', file);
    process.exit(1);
  }
  const { parseDotenv } = require('./config/env');
  const vars = parseDotenv(fs.readFileSync(file, 'utf8'));
  console.log('--- Existing Keys from backend/.env ---');
  console.log('AUDIT_HMAC_KEY=' + (vars.AUDIT_HMAC_KEY || '(not set)'));
  console.log('FILE_ENC_KEY=' + (vars.FILE_ENC_KEY || '(not set)'));
  console.log('---------------------------------------');
  console.log('Use these if deploying with existing encrypted documents/audit logs.');
  process.exit(0);
}

if (fs.existsSync(file)) {
  console.log('.env already exists; leaving it alone to protect existing encrypted data.');
  console.log('To generate fresh keys for cloud deployment (e.g. Render), run:');
  console.log('  npm run init -- --generate');
  console.log('To view existing local keys for production migration, run:');
  console.log('  npm run init -- --show-existing');
  process.exit(0);
}

const fileKey = key();
let auditKey = key();
while (auditKey === fileKey) auditKey = key();

fs.writeFileSync(file, [
  '# Generated by "npm run init". Never commit. Losing FILE_ENC_KEY loses every document.',
  `FILE_ENC_KEY=${fileKey}`,
  `AUDIT_HMAC_KEY=${auditKey}`,
  '# Code required to self-register as Administrator (12+ chars). Empty = admin sign-up disabled.',
  'ADMIN_REGISTRATION_CODE=',
  'PORT=3000',
  'HOST=127.0.0.1',
  '# Set to 1 when served over HTTPS (adds Secure cookies + HSTS). TRUST_PROXY=1 only behind a proxy you control.',
  'COOKIE_SECURE=0',
  'TRUST_PROXY=0',
  'MAX_UPLOAD_MB=10',
  'RETENTION_DAYS=30',
  '',
].join('\n'), { mode: 0o600 });
console.log('Wrote', file);
